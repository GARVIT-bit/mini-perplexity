"""Benchmark: HNSW vs exact brute-force vector search on the real index.

recall@10 = of the 10 chunks brute force returns (the true nearest), how many
HNSW also returns. Measured for several ef values (the speed/recall dial).

Queries: 300 text snippets (12 words from the middle of random chunks, seeded)
plus the hand-written test questions, all embedded with MiniLM, so the query
vectors look like real query vectors rather than random noise.

    python -m bench.hnsw --index data/index
"""
from __future__ import annotations

import argparse
import os
import random
import statistics
import tempfile
import time
from datetime import date

import numpy as np

from indexer.embed import Embedder
from indexer.index import InvertedIndex
from retrieval.hnsw import EF_CONSTRUCTION, M, HNSWIndex
from retrieval.vector import BruteForceIndex

QUESTIONS = [
    "how does asyncio gather work", "what is a strangler fig application", "os.path.join",
    "what is a feature toggle", "how do I read a csv file", "run several things at the same time",
    "replace an old system gradually without a big rewrite", "turn text into numbers",
]
EFS = [10, 20, 50, 100, 200, 400]


def make_queries(chunks, n: int, seed: int) -> list[str]:
    rng = random.Random(seed)
    out = []
    for c in rng.sample(chunks, n):
        words = c.text.split()
        start = max(0, len(words) // 2 - 6)
        out.append(" ".join(words[start:start + 12]))
    return out + QUESTIONS


def timed(search, queries, k: int) -> tuple[list[list[int]], list[float]]:
    ids, ms = [], []
    for q in queries:
        t = time.perf_counter()
        hits = search(q, k)
        ms.append((time.perf_counter() - t) * 1000)
        ids.append([i for i, _ in hits])
    return ids, ms


def pct(xs: list[float], p: float) -> float:
    return float(np.percentile(xs, p))


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--index", default="data/index")
    p.add_argument("--queries", type=int, default=300)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("-k", type=int, default=10)
    p.add_argument("--out", default="bench/results/hnsw.md")
    args = p.parse_args()

    chunks = InvertedIndex.load_chunks(args.index)
    exact = BruteForceIndex.load(args.index)
    texts = make_queries(chunks, args.queries, args.seed)
    qvecs = Embedder().encode(texts)

    t0 = time.perf_counter()
    hnsw = HNSWIndex.build(exact.vectors)
    build_s = time.perf_counter() - t0
    with tempfile.TemporaryDirectory() as tmp:          # only to measure the file size
        hnsw.save(tmp)
        size = os.path.getsize(os.path.join(tmp, "hnsw.bin"))

    for q in qvecs[:20]:                       # warm caches before timing anything
        exact.search(q, args.k)
        hnsw.search(q, args.k)
    truth, exact_ms = timed(exact.search, qvecs, args.k)

    rows = []
    for ef in EFS:
        hnsw.set_ef(ef)
        got, ms = timed(hnsw.search, qvecs, args.k)
        recall = sum(len(set(t) & set(g)) for t, g in zip(truth, got)) / (args.k * len(truth))
        rows.append((ef, recall, statistics.median(ms), pct(ms, 99)))

    lines = [
        f"# HNSW vs brute force ({date.today().isoformat()})", "",
        f"Corpus: `{args.index}`: {exact.n} vectors x {exact.dim} dims. "
        f"{len(texts)} queries ({args.queries} snippets, seed {args.seed}, + {len(QUESTIONS)} questions).",
        f"Generated by `python -m bench.hnsw --index {args.index}`.", "",
        f"HNSW build: M={M}, ef_construction={EF_CONSTRUCTION}, 1 thread: {build_s:.1f} s, "
        f"index file {size / 1e6:.1f} MB (raw vectors: {exact.vectors.nbytes / 1e6:.1f} MB).", "",
        f"| search | recall@{args.k} | median ms | p99 ms |", "|---|---:|---:|---:|",
        f"| brute force (exact) | 1.000 | {statistics.median(exact_ms):.3f} | {pct(exact_ms, 99):.3f} |",
        *(f"| HNSW ef={ef} | {r:.3f} | {med:.3f} | {p99:.3f} |" for ef, r, med, p99 in rows),
    ]
    report = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(report)
    print(report)


if __name__ == "__main__":
    main()
