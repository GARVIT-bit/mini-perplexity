"""Benchmark: how much does delta + varint shrink the postings, and what does
decoding cost at query time?

Compares the same postings stored five ways, measures what each in-memory
form costs in RAM, then times BM25 queries on a plain dict vs the compressed
blob. Reads chunks from a built index
(no re-parsing) and writes a markdown table to bench/results/compression.md.

    python -m bench.compression --index data/index
"""
from __future__ import annotations

import argparse
import gzip
import json
import os
import statistics
import time
import tracemalloc
from datetime import date

from indexer.compress import CompressedPostings, decode_postings, encode_varint
from indexer.index import InvertedIndex
from retrieval.bm25 import BM25

QUERIES = [
    "how does asyncio gather work", "os.path.join", "how do I read a csv file",
    "what is a strangler fig application", "what is a feature toggle", "regular expression groups",
    "continuous integration", "unit test mock", "dataclass default factory", "microservices",
]


def plain_varint_size(postings) -> int:
    """Varint without delta: store each id as-is."""
    buf = bytearray()
    for plist in postings.values():
        for cid, tf in plist:
            encode_varint(cid, buf)
            encode_varint(tf - 1, buf)
    return len(buf)


def time_queries(bm25: BM25, repeats: int) -> list[float]:
    """Per-query latency in ms, median over repeats (first run warms caches)."""
    out = []
    for q in QUERIES:
        bm25.search(q, k=10)
        runs = []
        for _ in range(repeats):
            t = time.perf_counter()
            bm25.search(q, k=10)
            runs.append((time.perf_counter() - t) * 1000)
        out.append(statistics.median(runs))
    return out


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--index", default="data/index")
    p.add_argument("--repeats", type=int, default=20)
    p.add_argument("--out", default="bench/results/compression.md")
    args = p.parse_args()

    chunks = InvertedIndex.load_chunks(args.index)
    # RAM actually held by each form (tracemalloc counts Python object overhead:
    # every tuple and list costs far more than the two ints inside it)
    tracemalloc.start()
    m0 = tracemalloc.get_traced_memory()[0]
    plain = InvertedIndex.build(chunks)                  # postings as a dict of lists
    m1 = tracemalloc.get_traced_memory()[0]
    comp = CompressedPostings.from_dict(plain.postings)
    m2 = tracemalloc.get_traced_memory()[0]
    tracemalloc.stop()
    ram_dict, ram_comp = m1 - m0, m2 - m1

    postings = plain.postings
    n_post = sum(len(pl) for pl in postings.values())
    sizes = {
        "JSON text": len(json.dumps(postings).encode()),
        "fixed int32 (id, tf)": 8 * n_post,
        "varint, no delta": plain_varint_size(postings),
        "delta + varint": len(comp.blob),
        "delta + varint + gzip": len(gzip.compress(comp.blob, 9)),
    }
    base = sizes["fixed int32 (id, tf)"]

    t = time.perf_counter()
    for term, (off, length, _) in comp.lexicon.items():
        decode_postings(comp.blob, off, off + length)
    decode_all = time.perf_counter() - t

    compressed_idx = InvertedIndex(comp, plain.doc_len, plain.chunks, plain.include_title)
    lat_dict = time_queries(BM25(plain), args.repeats)
    lat_comp = time_queries(BM25(compressed_idx), args.repeats)

    lines = [
        f"# Postings compression ({date.today().isoformat()})",
        "",
        f"Corpus: `{args.index}`: {plain.n_docs} chunks, {len(postings)} terms, {n_post} postings.",
        f"Generated by `python -m bench.compression --index {args.index}`.",
        "",
        "| encoding | bytes | bytes/posting | vs int32 |",
        "|---|---:|---:|---:|",
        *(f"| {name} | {size:,} | {size / n_post:.2f} | {size / base:.0%} |" for name, size in sizes.items()),
        "",
        "In memory (tracemalloc, includes Python object overhead):",
        "",
        "| postings in memory | MB | bytes/posting |",
        "|---|---:|---:|",
        f"| plain dict of lists of tuples | {ram_dict / 1e6:.1f} | {ram_dict / n_post:.1f} |",
        f"| delta + varint blob + lexicon | {ram_comp / 1e6:.1f} | {ram_comp / n_post:.1f} |",
        "",
        f"Decode every postings list once: {decode_all * 1000:.0f} ms "
        f"({decode_all / n_post * 1e9:.0f} ns/posting, pure Python).",
        "",
        f"BM25 top-10 latency over {len(QUERIES)} queries (median of {args.repeats} runs each):",
        "",
        "| postings in memory | mean ms | max ms |",
        "|---|---:|---:|",
        f"| plain dict of lists | {statistics.mean(lat_dict):.2f} | {max(lat_dict):.2f} |",
        f"| delta + varint blob | {statistics.mean(lat_comp):.2f} | {max(lat_comp):.2f} |",
    ]
    report = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(report)
    print(report)


if __name__ == "__main__":
    main()
