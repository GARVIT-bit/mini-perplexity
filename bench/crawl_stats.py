"""Benchmark: crawl and corpus numbers, recomputed from the crawl's own files.

Sources (nothing typed in by hand):
  data/crawl.db         status of every URL the crawler saw (done/failed/skipped/pending)
  crawl log files       one "done: {...}" line per crawler run -> pages, seconds per run
  data/pages            stored pages -> parser survival counts (with --parse; ~0.5 s/page)
  data/index/meta.json  chunks in the built index

    python -m bench.crawl_stats --logs data/crawl.log data/crawl-2.log --parse
"""
from __future__ import annotations

import argparse
import ast
import json
import os
import re
import sqlite3
from collections import Counter, defaultdict
from datetime import date

_DONE = re.compile(r"done: (\{.*\})")


def run_lines(paths: list[str]) -> list[dict]:
    runs = []
    for path in paths:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = _DONE.search(line)
                if m:
                    runs.append({"log": os.path.basename(path), **ast.literal_eval(m.group(1))})
    return runs


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--db", default="data/crawl.db")
    p.add_argument("--pages", default="data/pages")
    p.add_argument("--index", default="data/index")
    p.add_argument("--logs", nargs="*", default=["data/crawl.log"])
    p.add_argument("--parse", action="store_true", help="also count what the parser keeps (slow)")
    p.add_argument("--out", default="bench/results/crawl_stats.md")
    args = p.parse_args()

    db = sqlite3.connect(args.db)
    by_host: dict[str, Counter] = defaultdict(Counter)
    reasons: Counter = Counter()
    for host, status, error, n in db.execute(
            "SELECT host, status, COALESCE(error, ''), COUNT(*) FROM frontier GROUP BY 1, 2, 3"):
        by_host[host][status] += n
        if status in ("failed", "skipped"):
            reasons[f"{status}: {error or 'unknown'}"] += n
    db.close()
    total = Counter()
    for c in by_host.values():
        total.update(c)
    attempted = total["done"] + total["failed"] + total["skipped"]

    lines = [f"# Crawl stats ({date.today().isoformat()})", "",
             f"Generated by `python -m bench.crawl_stats --db {args.db} --pages {args.pages} "
             f"--index {args.index} --logs {' '.join(args.logs)}{' --parse' if args.parse else ''}`.", "",
             "## Runs (from crawler logs)", "",
             "| log | pages fetched | seconds | pages/s |", "|---|---:|---:|---:|"]
    runs = run_lines(args.logs)
    for r in runs:
        lines.append(f"| {r['log']} | {r['fetched']} | {r['seconds']} | {r['fetched'] / r['seconds']:.2f} |")
    if runs:
        f, s = sum(r["fetched"] for r in runs), sum(r["seconds"] for r in runs)
        lines.append(f"| **total** | **{f}** | **{s:.0f}** | **{f / s:.2f}** |")

    lines += ["", "## URL outcomes (from crawl.db)", "",
              "| host | done | failed | skipped | still pending |", "|---|---:|---:|---:|---:|"]
    for host, c in sorted(by_host.items()):
        lines.append(f"| {host} | {c['done']} | {c['failed']} | {c['skipped']} | {c['pending']} |")
    lines += ["", f"Of {attempted} URLs attempted: {total['done'] / attempted:.1%} fetched, "
                  f"{total['failed'] / attempted:.1%} failed, {total['skipped'] / attempted:.1%} skipped.", ""]
    lines += [f"- {k}: {v}" for k, v in reasons.most_common()]

    if args.parse:
        from crawler.store import iter_pages
        from indexer.parse import parse_pages
        stats: Counter = Counter()
        words = sum(d.n_words for d in parse_pages(iter_pages(args.pages), stats=stats))
        lines += ["", "## Parser (from data/pages)", "",
                  f"{stats['pages']} stored pages -> {stats['kept']} kept "
                  f"({stats['kept'] / max(stats['pages'], 1):.0%}), avg {words / max(stats['kept'], 1):.0f} words.", ""]
        lines += [f"- {k}: {v}" for k, v in stats.most_common() if k not in ("pages", "kept")]

    meta_path = os.path.join(args.index, "meta.json")
    if os.path.exists(meta_path):
        with open(meta_path, encoding="utf-8") as fh:
            meta = json.load(fh)
        lines += ["", f"Index `{args.index}`: {meta['n_docs']} chunks."]

    report = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(report)
    print(report)


if __name__ == "__main__":
    main()
